/* Solo lectura. Ejecutar en la base donde viven las cotizaciones de producción. */
SET NOCOUNT ON;
IF OBJECT_ID(N'dbo.COT_ENC', N'U') IS NULL OR OBJECT_ID(N'dbo.COT_DET', N'U') IS NULL
    THROW 55000, 'No existen las tablas de cotizaciones en la base actual.', 1;

SELECT DB_NAME() AS BASE_ACTUAL, e.ID_EMPRESA, e.ID_COTIZACION, e.FECHA,
       e.MONEDA, e.IMPORTE_BRUTO, e.DESCUENTO_TOTAL, e.SUBTOTAL,
       e.IMPUESTO_TOTAL, e.TOTAL,
       SUM(d.TOTAL) AS SUMA_LINEAS,
       SUM(ROUND(d.CANTIDAD * ROUND(d.PRECIO_UNITARIO, 2), 2)) AS BRUTO_CON_PRECIO_VISIBLE
FROM dbo.COT_ENC AS e
JOIN dbo.COT_DET AS d
  ON d.ID_EMPRESA = e.ID_EMPRESA AND d.ID_COTIZACION = e.ID_COTIZACION
WHERE e.ID_EMPRESA = N'BOLIK' AND e.ID_COTIZACION = N'COT-BO-00000001'
GROUP BY e.ID_EMPRESA, e.ID_COTIZACION, e.FECHA, e.MONEDA,
         e.IMPORTE_BRUTO, e.DESCUENTO_TOTAL, e.SUBTOTAL, e.IMPUESTO_TOTAL, e.TOTAL;

SELECT d.LINEA, d.ITEM_CODE, d.CANTIDAD, d.PRECIO_UNITARIO,
       ROUND(d.PRECIO_UNITARIO, 2) AS PRECIO_VISIBLE,
       d.DESCUENTO_PORCENTAJE, d.IMPORTE_BRUTO, d.DESCUENTO_MONTO,
       d.SUBTOTAL, d.IMPUESTO_MONTO, d.TOTAL,
       ROUND(d.CANTIDAD * ROUND(d.PRECIO_UNITARIO, 2), 2) AS TOTAL_SIN_IVA_ADICIONAL
FROM dbo.COT_DET AS d
WHERE d.ID_EMPRESA = N'BOLIK' AND d.ID_COTIZACION = N'COT-BO-00000001'
ORDER BY d.LINEA;

SELECT TOP (100) e.ID_EMPRESA, e.ID_COTIZACION, e.FECHA,
       e.IMPUESTO_TOTAL, e.TOTAL,
       SUM(d.TOTAL) AS SUMA_LINEAS
FROM dbo.COT_ENC AS e
JOIN dbo.COT_DET AS d
  ON d.ID_EMPRESA = e.ID_EMPRESA AND d.ID_COTIZACION = e.ID_COTIZACION
WHERE e.IMPUESTO_TOTAL <> 0
GROUP BY e.ID_EMPRESA, e.ID_COTIZACION, e.FECHA, e.IMPUESTO_TOTAL, e.TOTAL
ORDER BY e.FECHA DESC, e.ID_COTIZACION;
